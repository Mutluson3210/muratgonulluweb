// VIDEO MODAL — YouTube IFrame API
// ============================
const modal       = document.getElementById('videoModal');
const modalClose  = document.getElementById('modalClose');
const modalTitle  = document.getElementById('modalTitle');
const modalArtist = document.getElementById('modalArtist');
const modalFallback = document.getElementById('modal-fallback');
const modalYtLink   = document.getElementById('modal-yt-link');

let ytPlayer    = null;
let ytApiReady  = false;
let pendingVideo = null;

// Called automatically by YouTube API when loaded
window.onYouTubeIframeAPIReady = function () {
  ytApiReady = true;
  if (pendingVideo) {
    createPlayer(pendingVideo);
    pendingVideo = null;
  }
};

function createPlayer(videoId) {
  // If player already exists, just load the new video to save resources and prevent DOM issues
  if (ytPlayer && typeof ytPlayer.loadVideoById === 'function') {
    modalFallback.style.display = 'none';
    ytPlayer.loadVideoById(videoId);
    return;
  }

  // Ensure the target div exists
  let wrap = document.getElementById('yt-player');
  if (!wrap) {
    wrap = document.createElement('div');
    wrap.id = 'yt-player';
    document.querySelector('.modal-video-wrap').prepend(wrap);
  }
  wrap.innerHTML = '';
  modalFallback.style.display = 'none';

  ytPlayer = new YT.Player('yt-player', {
    videoId,
    playerVars: { autoplay: 1, rel: 0, modestbranding: 1 },
    events: {
      onError: function (e) {
        // 100: not found, 101/150/153: embedding not allowed
        if ([100, 101, 150, 153].includes(e.data)) {
          showFallback(videoId);
        }
      }
    }
  });
}

function showFallback(videoId) {
  if (ytPlayer) { ytPlayer.destroy(); ytPlayer = null; }
  modalYtLink.href = `https://www.youtube.com/watch?v=${videoId}`;
  modalFallback.style.display = 'flex';
}

function openModal(videoId, title, artist) {
  modalTitle.textContent  = title  || '';
  modalArtist.textContent = artist || '';
  modalYtLink.href = `https://www.youtube.com/watch?v=${videoId}`;
  modalFallback.style.display = 'none';
  modal.classList.add('active');
  document.body.style.overflow = 'hidden';

  if (window.YT && window.YT.Player) {
    ytApiReady = true;
  }

  if (ytApiReady) {
    createPlayer(videoId);
  } else {
    pendingVideo = videoId;
  }
}

function closeModal() {
  modal.classList.remove('active');
  document.body.style.overflow = '';
  if (ytPlayer && typeof ytPlayer.stopVideo === 'function') {
    ytPlayer.stopVideo();
  }
  modalFallback.style.display = 'none';
}

modalClose.addEventListener('click', closeModal);
modal.addEventListener('click', (e) => { if (e.target === modal) closeModal(); });
document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeModal(); });

